// Generates the two Unicode tables text/ uses (spec 06 §3.2 rule 4, §3.5):
//   src/text/line-break-classes.ts  UAX #14 classes OP CL CP EX IS NS (CJ folded into NS: strict
//                                   kinsoku keeps small kana and the long-vowel mark off a line
//                                   start), SY HY BA and NU, as code-point ranges;
//   src/text/bidi-strong.ts         Bidi_Class L and R/AL (UAX #9 strong types), as ranges.
// Sources: the dev dependencies `linebreak` (its UnicodeTrie of LineBreak.txt) and `bidi-js`.
// Dev-time only; the outputs are committed. Run: node tools/gen-text-tables.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import * as prettier from 'prettier';

const PKG = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(PKG, 'package.json'));
/** @type {new (data: Uint8Array) => { get(cp: number): number }} */
const UnicodeTrie = require('unicode-trie');
/** @type {() => { getBidiCharTypeName(ch: string): string }} */
const bidiFactory = require('bidi-js');

const lbSrc = readFileSync(path.join(PKG, 'node_modules/linebreak/dist/main.cjs'), 'utf8');
const lbVersion = JSON.parse(readFileSync(path.join(PKG, 'node_modules/linebreak/package.json'), 'utf8')).version;
const bidiVersion = JSON.parse(readFileSync(path.join(PKG, 'node_modules/bidi-js/package.json'), 'utf8')).version;
const m = lbSrc.match(/toByteArray\)?\("([^"]+)"\)/);
if (!m?.[1]) throw new Error('linebreak class trie not found');
const trie = new UnicodeTrie(Buffer.from(m[1], 'base64'));

// linebreak's class numbers (its classes.js) → ours (text/line-break-classes.ts `LB`).
const LB_FROM = new Map([
  [0, 1], // OP
  [1, 2], // CL
  [2, 3], // CP
  [6, 4], // EX
  [8, 5], // IS
  [5, 6], // NS
  [35, 6], // CJ → NS (strict)
  [7, 7], // SY
  [16, 8], // HY
  [17, 9], // BA
  [11, 10], // NU
]);

/**
 * @param {(cp: number) => number} classOf
 * @returns {number[]} flat [start, end, class, …], consecutive equal classes merged, class 0 dropped
 */
function ranges(classOf) {
  /** @type {number[]} */
  const out = [];
  let start = 0;
  let cur = classOf(0);
  for (let cp = 1; cp <= 0x110000; cp++) {
    const c = cp <= 0x10ffff ? classOf(cp) : -1;
    if (c !== cur) {
      if (cur !== 0) out.push(start, cp - 1, cur);
      start = cp;
      cur = c;
    }
  }
  return out;
}

/** Writes `code` formatted with the repo's Prettier config. @param {string} file @param {string} code */
async function write(file, code) {
  const options = (await prettier.resolveConfig(file)) ?? {};
  writeFileSync(file, await prettier.format(code, { ...options, filepath: file }));
}

/** @param {number[]} flat */
function format(flat) {
  const rows = [];
  for (let i = 0; i < flat.length; i += 24)
    rows.push(
      '  ' +
        flat
          .slice(i, i + 24)
          .map((n) => `0x${n.toString(16)}`)
          .join(', ') +
        ',',
    );
  return rows.join('\n');
}

const lb = ranges((cp) => LB_FROM.get(trie.get(cp)) ?? 0);
await write(
  path.join(PKG, 'src/text/line-break-classes.ts'),
  `// Generated by tools/gen-text-tables.mjs from linebreak ${lbVersion} (UAX #14 LineBreak.txt); do not edit.
// Code-point ranges of the UAX #14 classes the word wrapper uses (spec 06 §3.2 rules 1 and 4),
// flat as [start, end, class, …], sorted. CJ is folded into NS (strict kinsoku).

/** Our class numbers; 0 = any other class. */
export const LB = Object.freeze({ Other: 0, OP: 1, CL: 2, CP: 3, EX: 4, IS: 5, NS: 6, SY: 7, HY: 8, BA: 9, NU: 10 } as const);
export type LineBreakClass = (typeof LB)[keyof typeof LB];

// prettier-ignore
export const LINE_BREAK_RANGES: readonly number[] = Object.freeze([
${format(lb)}
]);
`,
);

const bidi = bidiFactory();
const strong = ranges((cp) => {
  const n = bidi.getBidiCharTypeName(String.fromCodePoint(cp));
  return n === 'L' ? 1 : n === 'R' || n === 'AL' ? 2 : 0;
});
await write(
  path.join(PKG, 'src/text/bidi-strong.ts'),
  `// Generated by tools/gen-text-tables.mjs from bidi-js ${bidiVersion} (UAX #9 Bidi_Class); do not edit.
// Code-point ranges of the strong bidi types, flat as [start, end, type, …], sorted:
// type 1 = L, type 2 = R or AL. Everything else is weak or neutral (spec 06 §3.5).

// prettier-ignore
export const BIDI_STRONG_RANGES: readonly number[] = Object.freeze([
${format(strong)}
]);
`,
);
console.log(`line-break ranges: ${String(lb.length / 3)}, bidi strong ranges: ${String(strong.length / 3)}`);
