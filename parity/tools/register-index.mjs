// Generates parity/register/README.md, the human view of the difference register (verification 01
// §9.1, spec 11 §7): id, title, kind, status and sign-off date per entry. Committed with each
// register change; register:check fails when it is stale.
//
//   node parity/tools/register-index.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';
import { REGISTER_DIR, loadRegister } from '../register/load.mjs';

/** @param {unknown} s */
const cell = (s) =>
  String(s ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');

/**
 * @param {import('../register/load.mjs').RegisterEntry[]} entries
 * @returns {string}
 */
export function renderIndex(entries) {
  /** @type {Record<string, number>} */
  const byStatus = {};
  for (const e of entries) byStatus[String(e.data['status'])] = (byStatus[String(e.data['status'])] ?? 0) + 1;
  return [
    '# Difference register',
    '',
    'Generated by `node parity/tools/register-index.mjs` from the `DR-*.yaml` files; do not edit.',
    'Format and workflow: verification 01 §9 (Work 01M4X7TCHFB862XGT68GPY071C). Check with `npm run register:check`.',
    '',
    `${entries.length} entries: ${Object.entries(byStatus)
      .sort()
      .map(([k, v]) => `${v} ${k}`)
      .join(', ')}.`,
    '',
    '| Id | Title | Kind | Status | Signed off |',
    '|---|---|---|---|---|',
    ...entries.map(
      (e) =>
        `| ${cell(e.data['id'])} | ${cell(e.data['title'])} | ${cell(e.data['kind'])} | ${cell(e.data['status'])} | ${cell(e.data['signed_off_at'] ?? '')} |`,
    ),
    '',
  ].join('\n');
}

/**
 * The index as committed: `renderIndex` formatted by lekhjs's prettier config (the repository's
 * format check covers it).
 * @param {import('../register/load.mjs').RegisterEntry[]} entries
 */
export async function formattedIndex(entries) {
  const file = path.join(REGISTER_DIR, 'README.md');
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(renderIndex(entries), { ...config, filepath: file });
}

if (import.meta.filename === path.resolve(process.argv[1] ?? '')) {
  const entries = loadRegister();
  writeFileSync(path.join(REGISTER_DIR, 'README.md'), await formattedIndex(entries));
  process.stdout.write(`wrote parity/register/README.md (${entries.length} entries)\n`);
}
